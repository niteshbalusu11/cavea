"""Bakes the renderer's glyph atlas (docs/04-renderer.md §12, DECISIONS.md D-33).

Run from the repository root inside the pinned shell:

    nix-shell tools/glyph-atlas --run 'python3 -I tools/glyph-atlas/bake.py'

Writes the multi-channel signed distance field atlas of Roboto Condensed
Medium to packages/renderer/assets/glyphs.png and its metrics to
crates/cavea-render/src/text/glyphs.rs. The output is deterministic: running
this again and finding no change in `git status` verifies the committed files.
"""

import json
import os
import shutil
import subprocess
import sys
import tempfile

from fontTools.ttLib import TTFont
from fontTools.ttLib.removeOverlaps import removeOverlaps

FONT = "RobotoCondensed-Medium.ttf"
# Digits, capitals, the space and the punctuation of seat labels. Lowercase
# and other text come from the dynamic atlas (04 §12).
CHARSET = "['0','9'],['A','Z'],' ','-','.','/'"
# Pixels per em in the atlas, and the width of the distance range in pixels.
EM_PX = 16
RANGE_PX = 3

ATLAS = "packages/renderer/assets/glyphs.png"
METRICS = "crates/cavea-render/src/text/glyphs.rs"


def number(v):
    """A Rust f32 literal for a binary fraction from the generator."""
    text = repr(float(v))
    return text if "e" not in text else f"{v:.9f}"


def main():
    font = os.path.join(os.environ["ROBOTO"], FONT)
    with tempfile.TemporaryDirectory() as tmp:
        merged = os.path.join(tmp, "font.ttf")
        tt = TTFont(font)
        version = tt["name"].getDebugName(5)
        removeOverlaps(tt)
        tt.save(merged)
        png = os.path.join(tmp, "atlas.png")
        layout = os.path.join(tmp, "atlas.json")
        subprocess.run(
            [
                "msdf-atlas-gen",
                "-font", merged,
                "-chars", CHARSET,
                "-type", "msdf",
                "-format", "png",
                "-imageout", png,
                "-json", layout,
                "-size", str(EM_PX),
                "-pxrange", str(RANGE_PX),
                "-yorigin", "top",
                "-threads", "1",
            ],
            check=True,
            stdout=subprocess.DEVNULL,
        )
        subprocess.run(
            ["oxipng", "-q", "-o", "max", "--strip", "all", "--zopfli", png],
            check=True,
        )
        shutil.copyfile(png, ATLAS)
        with open(layout, encoding="utf-8") as f:
            data = json.load(f)

    atlas = data["atlas"]
    cap = TTFont(font)["OS/2"].sCapHeight / TTFont(font)["head"].unitsPerEm
    rows = []
    for g in sorted(data["glyphs"], key=lambda g: g["unicode"]):
        zero = {"left": 0, "top": 0, "right": 0, "bottom": 0}
        p, a = g.get("planeBounds", zero), g.get("atlasBounds", zero)
        side = lambda b: ", ".join(number(b[k]) for k in ("left", "top", "right", "bottom"))
        rows.append(
            f"    Glyph {{ ch: b{chr(g['unicode'])!r}, advance: {number(g['advance'])}, "
            f"plane: [{side(p)}], atlas: [{side(a)}] }},"
        )
    rust = f"""//! Generated by `tools/glyph-atlas/bake.py`; do not edit. The metrics of
//! `packages/renderer/assets/glyphs.png`: {FONT} {version}, overlaps
//! removed, {EM_PX} px per em, a distance range of {RANGE_PX} px.
#![allow(
    clippy::excessive_precision,
    reason = "the generator's values are exact binary fractions"
)]

use super::Glyph;

/// The atlas in pixels.
pub const ATLAS_SIZE: [u32; 2] = [{atlas['width']}, {atlas['height']}];
/// The width of the distance range in em: a median of 0 or 1 is this far
/// outside or inside the edge.
pub const RANGE_EM: f32 = {number(RANGE_PX / EM_PX)};
/// The capital height in em, which labels are centred on.
pub const CAP_HEIGHT_EM: f32 = {number(cap)};

/// By character. Plane bounds in em from the pen position on the baseline,
/// y down; atlas bounds in pixels from the top left.
#[rustfmt::skip]
pub const GLYPHS: [Glyph; {len(rows)}] = [
{chr(10).join(rows)}
];
"""
    with open(METRICS, "w", encoding="utf-8") as f:
        f.write(rust)
    print(f"{ATLAS}: {atlas['width']} x {atlas['height']}, {os.path.getsize(ATLAS)} B; {METRICS}: {len(rows)} glyphs")


if __name__ == "__main__":
    sys.exit(main())
