// Builds the public documentation site into `apps/docs/dist/`: plain static
// files that any static host serves (D-82). Run from anywhere:
//
//   bun apps/docs/src/build.ts [--out DIR] [--var name=value …]
//
// Sources: `content/**/*.md` (written by hand), the server API reference
// (generated from `crates/cavea-server/openapi.json`, src/api.ts) and the
// changelog (from `CHANGELOG.md`). Variables (`{{image}}` and the like) come
// from `site.json`; `--var` overrides one for a local build, as the
// quick-start check does. The build fails on a broken internal link or
// anchor, an unknown variable, a page missing from the navigation, an
// internal specification reference left in a generated page, or an error
// reference that does not match the server (src/errors.ts).

import { cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, posix, relative } from "node:path";
import { apiPages, problemCodes, type Doc } from "./api.ts";
import { compare, parseCatalogue, scanReasons } from "./errors.ts";
import { layout, type NavSection } from "./layout.ts";
import { plain, render, substitute, type Heading } from "./markdown.ts";

const HERE = join(import.meta.dir, "..");
const ROOT = join(HERE, "../..");
const started = performance.now();

interface Site {
  title: string;
  published: boolean;
  vars: Record<string, string>;
  nav: Array<{ section: string; pages?: string[]; planned?: string }>;
}

interface Page {
  /** As under `content/`, such as `concepts/holds.md`. */
  path: string;
  source: string;
  generated: boolean;
}

function args(): { out: string; vars: Record<string, string> } {
  const argv = Bun.argv.slice(2);
  let out = join(HERE, "dist");
  const vars: Record<string, string> = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const next = argv[i + 1];
    if (a === "--out" && next !== undefined) {
      out = next;
      i++;
    } else if (a === "--var" && next !== undefined) {
      const at = next.indexOf("=");
      if (at < 1) throw new Error(`--var takes name=value, not ${next}`);
      vars[next.slice(0, at)] = next.slice(at + 1);
      i++;
    } else {
      throw new Error(`unknown argument ${a}`);
    }
  }
  return { out, vars };
}

async function markdownFiles(dir: string, base = dir): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await markdownFiles(path, base)));
    else if (entry.name.endsWith(".md")) out.push(relative(base, path).split("\\").join("/"));
  }
  return out.toSorted();
}

/** `CHANGELOG.md` as a page, without the paragraph addressed to the repository's contributors. */
function changelog(text: string): string {
  const body = text
    .replace(/^# Changelog\n/, "")
    .split("\n\n")
    .filter((p) => !p.startsWith("Pull requests do not edit this file"))
    .join("\n\n")
    // References to the internal specifications, such as (`docs/05-web-sdk.md`).
    .replace(/\s*\(`docs\/[^`]+`[^)]*\)/g, "")
    .trim();
  return `# Changelog\n\n${body}\n`;
}

const htmlPath = (md: string): string => md.replace(/\.md$/, ".html");

export interface Built {
  out: string;
  pages: number;
  bytes: number;
  ms: number;
}

export async function build(
  options: { out?: string; vars?: Record<string, string> } = {},
): Promise<Built> {
  const site = JSON.parse(await readFile(join(HERE, "site.json"), "utf8")) as Site;
  const vars = { ...site.vars, ...options.vars };
  const out = options.out ?? join(HERE, "dist");

  // Sources.
  const pages: Page[] = [];
  for (const path of await markdownFiles(join(HERE, "content"))) {
    pages.push({
      path,
      source: await readFile(join(HERE, "content", path), "utf8"),
      generated: false,
    });
  }
  const doc = JSON.parse(
    await readFile(join(ROOT, "crates/cavea-server/openapi.json"), "utf8"),
  ) as Doc;
  for (const [path, source] of apiPages(doc)) pages.push({ path, source, generated: true });
  pages.push({
    path: "reference/changelog.md",
    source: changelog(await readFile(join(ROOT, "CHANGELOG.md"), "utf8")),
    generated: true,
  });

  // The error reference against the server.
  const errorsPage = pages.find((p) => p.path === "reference/errors.md");
  if (errorsPage === undefined) throw new Error("content/reference/errors.md is missing");
  const problems = compare(
    parseCatalogue(errorsPage.source),
    problemCodes(doc),
    await scanReasons(ROOT),
  );
  if (problems.length > 0) {
    throw new Error(`the error reference does not match the server:\n  ${problems.join("\n  ")}`);
  }

  // Navigation: every page is in it exactly once, and it names no missing page.
  const byPath = new Map(pages.map((p) => [p.path, p]));
  const order: string[] = [];
  for (const s of site.nav) {
    for (const p of s.pages ?? []) {
      if (!byPath.has(p)) throw new Error(`site.json names ${p}, which does not exist`);
      if (order.includes(p)) throw new Error(`site.json names ${p} twice`);
      order.push(p);
    }
  }
  const missing = pages.filter((p) => !order.includes(p.path)).map((p) => p.path);
  if (missing.length > 0)
    throw new Error(`pages missing from site.json's nav: ${missing.join(", ")}`);

  // Render.
  const rendered = new Map<string, ReturnType<typeof render>>();
  for (const page of pages) {
    const source = substitute(page.source, vars, page.path);
    const r = render(source, page.path);
    if (page.generated && /§|\bD-\d+\b|docs\/\d\d-/.test(r.html)) {
      const at = r.html.match(/.{0,60}(?:§|\bD-\d+\b|docs\/\d\d-).{0,40}/)?.[0];
      throw new Error(
        `${page.path}: an internal specification reference reached the page: …${at}… (apps/docs/src/api.ts, customer())`,
      );
    }
    rendered.set(page.path, r);
  }
  const titleOf = (p: string): string => rendered.get(p)?.title ?? p;
  const nav: NavSection[] = site.nav.map((s) => ({
    section: s.section,
    pages: (s.pages ?? []).map((p) => ({ path: htmlPath(p), title: titleOf(p) })),
    planned: s.planned,
  }));

  await rm(out, { recursive: true, force: true });
  await mkdir(out, { recursive: true });

  const files = new Map<string, string>();
  const search: Array<{ t: string; s: string; u: string; x: string }> = [];
  for (const [i, path] of order.entries()) {
    const r = rendered.get(path);
    if (r === undefined) continue;
    const prev = order[i - 1];
    const next = order[i + 1];
    const html = layout({
      site: site.title,
      path: htmlPath(path),
      title: r.title,
      description: r.description,
      content: r.html,
      headings: r.headings,
      nav,
      published: site.published,
      prev: prev === undefined ? undefined : { path: htmlPath(prev), title: titleOf(prev) },
      next: next === undefined ? undefined : { path: htmlPath(next), title: titleOf(next) },
    });
    files.set(htmlPath(path), html);
    search.push(...sections(htmlPath(path), r.title, r.html, r.headings));
  }

  // Static files, and the sample chart document the quick start offers.
  await cp(join(HERE, "static"), out, { recursive: true });
  await mkdir(join(out, "samples"), { recursive: true });
  await cp(
    join(ROOT, "apps/console/src/designer/templates/theatre.json"),
    join(out, "samples/theatre.json"),
  );
  for (const [path, html] of files) {
    await mkdir(dirname(join(out, path)), { recursive: true });
    await writeFile(join(out, path), html);
  }
  await writeFile(join(out, "search.json"), JSON.stringify(search));
  await writeFile(join(out, "404.html"), notFound(site.title, nav, site.published));

  const broken = await checkLinks(out, files);
  if (broken.length > 0) {
    throw new Error(`broken internal links:\n  ${broken.join("\n  ")}`);
  }
  let bytes = 0;
  for (const f of await allFiles(out))
    bytes += (await Bun.file(join(out, f)).arrayBuffer()).byteLength;
  return { out, pages: files.size, bytes, ms: performance.now() - started };
}

/** One search entry per section: the page, its heading, and the section's text. */
function sections(
  url: string,
  title: string,
  html: string,
  headings: Heading[],
): Array<{ t: string; s: string; u: string; x: string }> {
  const out: Array<{ t: string; s: string; u: string; x: string }> = [];
  const parts = html.split(/(?=<h[23] id=")/);
  for (const part of parts) {
    const id = part.match(/^<h[23] id="([^"]+)"/)?.[1];
    const heading = id === undefined ? undefined : headings.find((h) => h.id === id);
    const text = plain(
      part.replace(/<a class="anchor"[^>]*>#<\/a>/g, "").replace(/<h1[\s\S]*?<\/h1>/, ""),
    );
    const body = heading === undefined ? text : text.slice(heading.text.length).trim();
    out.push({
      t: title,
      s: heading?.text ?? "",
      u: id === undefined ? url : `${url}#${id}`,
      x: body.slice(0, 600),
    });
  }
  return out;
}

function notFound(site: string, nav: NavSection[], published: boolean): string {
  return layout({
    site,
    path: "404.html",
    title: "Page not found",
    description: "",
    content: `<h1 id="page-not-found">Page not found</h1>\n<p>No page is at this address. Start from the <a href="index.html">documentation's home page</a>, or search.</p>`,
    headings: [],
    nav,
    published,
    prev: undefined,
    next: undefined,
    // Served at any depth by a host: absolute links from the site's root.
    absolute: true,
  });
}

async function allFiles(dir: string, base = dir): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await allFiles(path, base)));
    else out.push(relative(base, path).split("\\").join("/"));
  }
  return out;
}

/** Every `href` and `src` within the site resolves to a file, and every `#anchor` to an id on its page. */
async function checkLinks(out: string, pages: Map<string, string>): Promise<string[]> {
  const exists = new Set(await allFiles(out));
  const ids = new Map<string, Set<string>>();
  for (const [path, html] of pages) {
    ids.set(path, new Set([...html.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1] ?? "")));
  }
  const broken: string[] = [];
  for (const [path, html] of pages) {
    for (const m of html.matchAll(/\s(?:href|src)="([^"]*)"/g)) {
      const link = (m[1] ?? "").replace(/&amp;/g, "&");
      if (/^[a-z][a-z0-9+.-]*:/i.test(link) || link.startsWith("//")) continue;
      const [file = "", hash] = link.split("#");
      const target = file === "" ? path : posix.normalize(posix.join(posix.dirname(path), file));
      if (target.startsWith("..") || !exists.has(target)) {
        broken.push(`${path}: ${link} (no file ${target})`);
        continue;
      }
      if (hash !== undefined && hash !== "" && !ids.get(target)?.has(decodeURIComponent(hash))) {
        broken.push(`${path}: ${link} (no id "${hash}" in ${target})`);
      }
    }
  }
  return broken;
}

if (import.meta.main) {
  const { out, vars } = args();
  const built = await build({ out, vars });
  const kb = (built.bytes / 1024).toFixed(0);
  console.log(
    `built ${built.pages} pages, ${kb} KiB, in ${(built.ms / 1000).toFixed(2)} s: ${relative(process.cwd(), built.out) || "."}`,
  );
}
