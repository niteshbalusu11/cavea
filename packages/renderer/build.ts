// The distributable build of `@cavea/renderer` (docs/05-web-sdk.md §1):
// `bun run build` in this package, after `cargo xtask build-web`. Writes
// `dist/`, which is the package a customer installs (`bun pm pack` in it):
//
// - `index.js`: ES module of the public API, not minified, with
//   `process.env.NODE_ENV` left for the customer's bundler;
// - `index.d.ts` and the declarations it reaches;
// - `cavea.min.js`: the script-tag build, a minified classic script setting
//   `window.Cavea`, production, its WASM and atlas pinned by hash;
// - `cavea_web_bg.wasm` and `glyphs.png`, beside both, which both reference as
//   `new URL("./…", import.meta.url)` (the script-tag build: its own URL);
// - `package.json`, from this one, pointing at the files above.
//
// It also checks `api.md`, the public declarations as one file, so that a
// change to the public API shows in a pull request's diff: the build fails
// while it is stale, and `bun run build --update-api` rewrites it.
import { createHash } from "node:crypto";
import { mkdir, readFile, rm, writeFile, copyFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { brotliCompressSync, constants } from "node:zlib";

const root = import.meta.dir;
const dist = join(root, "dist");
const WASM = "cavea_web_bg.wasm";
const ATLAS = "glyphs.png";
/** How the source names the files (`src/` beside `wasm/` and `assets/`), and how `dist/` does. */
const URLS: Array<[string, string]> = [
  [`"../wasm/${WASM}"`, `"./${WASM}"`],
  [`"../assets/${ATLAS}"`, `"./${ATLAS}"`],
];

/** `code` with the source's asset URLs pointing beside the bundle; each must occur once. */
function relocate(code: string, file: string): string {
  for (const [from, to] of URLS) {
    if (code.split(from).length !== 2) {
      throw new Error(`${file}: expected ${from} once`);
    }
    code = code.replace(from, to);
  }
  return code;
}

async function bundle(options: Parameters<typeof Bun.build>[0]): Promise<string> {
  const result = await Bun.build({ target: "browser", ...options });
  const [output] = result.outputs;
  if (!result.success || output === undefined || result.outputs.length !== 1) {
    throw new AggregateError(result.logs, "bun build failed");
  }
  return output.text();
}

const sri = async (file: string): Promise<string> =>
  `sha384-${createHash("sha384")
    .update(await readFile(file))
    .digest("base64")}`;

/** The ES module: what bundlers and `<script type="module">` load. */
export async function buildModule(): Promise<string> {
  const code = await bundle({ entrypoints: [join(root, "src/index.ts")], format: "esm" });
  return relocate(code, "index.js");
}

/**
 * The script-tag build: an IIFE inside a function that reads its own URL
 * first (`document.currentScript` is only set while a classic script runs;
 * a module script or a loader that evaluates the text has none, and the
 * page's URL is used, so pass `assets.baseUrl` there).
 */
export async function buildGlobal(): Promise<string> {
  const integrity = {
    wasm: await sri(join(root, "wasm", WASM)),
    atlas: await sri(join(root, "assets", ATLAS)),
  };
  const code = await bundle({
    entrypoints: [join(root, "src/global.ts")],
    format: "iife",
    minify: true,
    define: {
      "process.env.NODE_ENV": '"production"',
      "import.meta.url": "caveaScriptUrl",
      CAVEA_INTEGRITY: JSON.stringify(integrity),
    },
  });
  const head =
    "var caveaScriptUrl=document.currentScript&&document.currentScript.src||document.baseURI;";
  return `(function(){${head}${relocate(code, "cavea.min.js").trim()}})();\n`;
}

/** `index.d.ts` and the declaration files it reaches, by name, with `.ts` imports as `.js`. */
async function declarations(): Promise<Map<string, string>> {
  const out = join(root, "../../target/tmp/renderer-dts");
  await rm(out, { recursive: true, force: true });
  const tsc = Bun.spawnSync(["tsc", "-p", "tsconfig.dist.json", "--outDir", out], {
    cwd: root,
    stdout: "inherit",
    stderr: "inherit",
  });
  if (tsc.exitCode !== 0) {
    throw new Error("tsc failed to emit declarations");
  }
  const files = new Map<string, string>();
  const visit = async (name: string): Promise<void> => {
    if (files.has(name)) {
      return;
    }
    const text = (await readFile(join(out, name), "utf8")).replaceAll(
      /(from "\.\/[^"]+)\.ts"/g,
      '$1.js"',
    );
    files.set(name, text);
    for (const [, next] of text.matchAll(/from "\.\/([^"]+)\.js"/g)) {
      await visit(`${next}.d.ts`);
    }
  };
  await visit("index.d.ts");
  return files;
}

/** The API report: every public declaration file, in name order, as one Markdown file. */
const report = (files: Map<string, string>): string =>
  "# `@cavea/renderer` public API\n\nGenerated by `packages/renderer/build.ts` from the declarations " +
  "the package ships; `bun run build --update-api` rewrites it. Review changes to it as API changes.\n" +
  [...files.keys()]
    .toSorted()
    .map((name) => `\n## ${name}\n\n\`\`\`ts\n${files.get(name)!.trim()}\n\`\`\`\n`)
    .join("");

const brotli = (bytes: Uint8Array): number =>
  brotliCompressSync(bytes, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } }).length;

/** `dist/package.json`: this package's identity, pointing at the built files. */
async function manifest(): Promise<string> {
  const source = JSON.parse(await readFile(join(root, "package.json"), "utf8")) as Record<
    string,
    unknown
  >;
  const pkg = {
    name: source["name"],
    version: source["version"],
    // Nothing is published before the release pipeline (OPS-001).
    private: true,
    description: "Seat map for ticketing sites: WebGL2 renderer compiled to WebAssembly",
    license: "UNLICENSED",
    type: "module",
    sideEffects: false,
    main: "./index.js",
    module: "./index.js",
    types: "./index.d.ts",
    exports: {
      ".": { types: "./index.d.ts", default: "./index.js" },
      "./cavea.min.js": "./cavea.min.js",
      [`./${WASM}`]: `./${WASM}`,
      [`./${ATLAS}`]: `./${ATLAS}`,
      "./package.json": "./package.json",
    },
  };
  return `${JSON.stringify(pkg, null, 2)}\n`;
}

async function main(): Promise<void> {
  try {
    await readFile(join(root, "wasm", WASM));
  } catch {
    throw new Error("packages/renderer/wasm is missing: run `cargo xtask build-web` first");
  }
  const update = process.argv.includes("--update-api");
  const types = await declarations();
  const api = report(types);
  const apiFile = join(root, "api.md");
  const committed = await readFile(apiFile, "utf8").catch(() => "");
  if (api !== committed && !update) {
    throw new Error(
      "packages/renderer/api.md is stale: the public API changed. Run `bun run build --update-api` " +
        "in packages/renderer and commit it",
    );
  }
  await rm(dist, { recursive: true, force: true });
  await mkdir(dist, { recursive: true });
  for (const [name, text] of types) {
    await mkdir(dirname(join(dist, name)), { recursive: true });
    await writeFile(join(dist, name), text);
  }
  await writeFile(join(dist, "index.js"), await buildModule());
  await writeFile(join(dist, "cavea.min.js"), await buildGlobal());
  await copyFile(join(root, "wasm", WASM), join(dist, WASM));
  await copyFile(join(root, "assets", ATLAS), join(dist, ATLAS));
  await copyFile(join(root, "assets", "OFL.txt"), join(dist, "OFL.txt"));
  await writeFile(join(dist, "package.json"), await manifest());
  if (update) {
    await writeFile(apiFile, api);
  }
  const global = await readFile(join(dist, "cavea.min.js"));
  console.log(
    `${relative(process.cwd(), dist)}: index.js, ${types.size} declaration files, cavea.min.js ` +
      `(${global.length} B, ${brotli(global)} B brotli; integrity ${await sri(join(dist, "cavea.min.js"))})`,
  );
}

if (import.meta.main) {
  await main();
}
