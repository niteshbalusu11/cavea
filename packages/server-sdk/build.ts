// The distributable build of `@cavea/server-sdk` (05 §15, the shape of D-58):
// `bun run build` in this package writes `dist/`, which is the package a
// customer installs (`bun pm pack` in it):
//
// - `index.js`: the public API as one ES module, not minified, no imports;
// - `index.d.ts` and the declarations it reaches;
// - `package.json`, from this one, pointing at the files above.
//
// It also checks `api.md`, the public declarations as one file, so that a
// change to the public API shows in a pull request's diff: the build fails
// while it is stale, and `bun run build --update-api` rewrites it. A change
// to the server's OpenAPI document reaches it through `generated.ts`.
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";

const root = import.meta.dir;
const dist = join(root, "dist");

async function bundle(): Promise<string> {
  const result = await Bun.build({
    entrypoints: [join(root, "src/index.ts")],
    target: "node",
    format: "esm",
  });
  const [output] = result.outputs;
  if (!result.success || output === undefined || result.outputs.length !== 1) {
    throw new AggregateError(result.logs, "bun build failed");
  }
  const code = await output.text();
  if (/^\s*import\b|\brequire\(/m.test(code)) {
    throw new Error("index.js imports something: the package has no runtime dependencies");
  }
  return code;
}

/** `index.d.ts` and the declaration files it reaches, by name, with `.ts` imports as `.js`. */
async function declarations(): Promise<Map<string, string>> {
  const out = join(root, "../../target/tmp/server-sdk-dts");
  await rm(out, { recursive: true, force: true });
  const tsc = Bun.spawnSync(["tsc", "-p", "tsconfig.dist.json", "--outDir", out], {
    cwd: root,
    stdout: "inherit",
    stderr: "inherit",
  });
  if (tsc.exitCode !== 0) {
    throw new Error("tsc failed to emit declarations");
  }
  const files = new Map<string, string>();
  const visit = async (name: string): Promise<void> => {
    if (files.has(name)) {
      return;
    }
    const text = (await readFile(join(out, name), "utf8")).replaceAll(
      /(from "\.\/[^"]+)\.ts"/g,
      '$1.js"',
    );
    files.set(name, text);
    for (const [, next] of text.matchAll(/from "\.\/([^"]+)\.js"/g)) {
      await visit(`${next}.d.ts`);
    }
  };
  await visit("index.d.ts");
  return files;
}

/** The API report: every public declaration file, in name order, as one Markdown file. */
const report = (files: Map<string, string>): string =>
  "# `@cavea/server-sdk` public API\n\nGenerated by `packages/server-sdk/build.ts` from the declarations " +
  "the package ships; `bun run build --update-api` rewrites it. Review changes to it as API changes.\n" +
  [...files.keys()]
    // oxlint-disable-next-line unicorn/no-array-sort -- a fresh copy; `toSorted` is ES2023, past the lib
    .sort()
    .map((name) => `\n## ${name}\n\n\`\`\`ts\n${files.get(name)!.trim()}\n\`\`\`\n`)
    .join("");

/** `dist/package.json`: this package's identity, pointing at the built files. */
async function manifest(): Promise<string> {
  const source = JSON.parse(await readFile(join(root, "package.json"), "utf8")) as Record<
    string,
    unknown
  >;
  const pkg = {
    name: source["name"],
    version: source["version"],
    // Nothing is published before the release pipeline (OPS-001).
    private: true,
    description:
      "Cavea server's REST API for a ticketing backend (Node 20.3+, bun). Holds a secret key: never in a browser",
    license: "UNLICENSED",
    type: "module",
    sideEffects: false,
    engines: { node: ">=20.3" },
    main: "./index.js",
    module: "./index.js",
    types: "./index.d.ts",
    exports: {
      ".": { types: "./index.d.ts", default: "./index.js" },
      "./package.json": "./package.json",
    },
  };
  return `${JSON.stringify(pkg, null, 2)}\n`;
}

async function main(): Promise<void> {
  const update = process.argv.includes("--update-api");
  const types = await declarations();
  const api = report(types);
  const apiFile = join(root, "api.md");
  const committed = await readFile(apiFile, "utf8").catch(() => "");
  if (api !== committed && !update) {
    throw new Error(
      "packages/server-sdk/api.md is stale: the public API changed. Run `bun run build --update-api` " +
        "in packages/server-sdk and commit it",
    );
  }
  await rm(dist, { recursive: true, force: true });
  await mkdir(dist, { recursive: true });
  for (const [name, text] of types) {
    await mkdir(dirname(join(dist, name)), { recursive: true });
    await writeFile(join(dist, name), text);
  }
  const code = await bundle();
  await writeFile(join(dist, "index.js"), code);
  await writeFile(join(dist, "package.json"), await manifest());
  if (update) {
    await writeFile(apiFile, api);
  }
  console.log(
    `${relative(process.cwd(), dist)}: index.js (${code.length} B), ${types.size} declaration files`,
  );
}

if (import.meta.main) {
  await main();
}
